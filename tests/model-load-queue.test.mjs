import assert from 'node:assert/strict';
import {createModelLoadQueue} from '../js/model-load-queue.js';
let sector='aurora',active=0,maxActive=0;const pending=[],started=[];
const loader={load(path,done,progress,fail){started.push(path);active++;maxActive=Math.max(maxActive,active);pending.push({done:()=>{active--;done({scene:path})},fail:()=>{active--;fail(Error('offline'))}})}};
const q=createModelLoadQueue({schedule:fn=>fn(),eligible:path=>path==='shared'||path===sector});
let mounted=0,errors=0;
const grave=q.load(loader,'graveyard',()=>mounted++);
const shared=q.load(loader,'shared',()=>mounted++);
assert.deepEqual(started,['shared'],'future sector cannot block shared assets');
const home=q.load(loader,'aurora',()=>mounted++);
pending.shift().done();assert.deepEqual(started,['shared','aurora']);pending.shift().done();await Promise.all([shared,home]);
sector='graveyard';q.pump();assert.equal(started.at(-1),'graveyard');pending.shift().done();await grave;
assert.equal(mounted,3);assert.equal(maxActive,1,'only one decode at a time');
const fail=q.load(loader,'shared',()=>{},undefined,()=>errors++);const next=q.load(loader,'shared',()=>mounted++);
pending.shift().fail();pending.shift().done();await Promise.all([fail,next]);assert.equal(errors,1);assert.equal(mounted,4);assert(!q.busy);
console.log('Model queue: sector gating, no head-of-line blocking, serial decode and error recovery passed.');

const order=[],scheduled=[];
const prioritized=createModelLoadQueue({schedule:fn=>scheduled.push(fn),priority:path=>path==='combat'?0:2});
const instant={load(path,done){order.push(path);done({})}};
const first=prioritized.load(instant,'initial');const decoration=prioritized.load(instant,'decoration');const combat=prioritized.load(instant,'combat');
while(scheduled.length)scheduled.shift()();await Promise.all([first,decoration,combat]);
assert.deepEqual(order,['initial','combat','decoration'],'combat assets precede optional scenery');
