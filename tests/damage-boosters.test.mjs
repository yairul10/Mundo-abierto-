import assert from 'node:assert/strict';
import {DAMAGE_BOOSTERS,damageBoosterTimers,damageBoosterMultiplier,tickDamageBoosters} from '../js/damage-boosters.js';
import {normalizeHangar,buyBooster,laserBoosterBonus,tickBoosters,boosterBonus} from '../js/hangar-systems.js';
import {offlineRoster} from '../js/pvp-loadout.js';
import {createHangarEditor,serializeHangarEditor} from '../js/pvp-hangar.js';
import {makeCombatPlayer,volley,stepCombat} from '../server/pvp/combat.mjs';
import {equip,importRoster} from '../server/pvp/world-rules.mjs';

assert.deepEqual(DAMAGE_BOOSTERS.map(b=>[b.price,b.seconds]),[[100000,300],[500000,300]]);
const pilot={gold:1000000};normalizeHangar(pilot);
assert(buyBooster(pilot,'damage2'));assert.equal(pilot.gold,900000);
assert.equal(laserBoosterBonus(pilot),2);
assert(buyBooster(pilot,'damage2'));assert.equal(pilot.boosters.damage2,600);
assert(buyBooster(pilot,'damage3'));assert.equal(pilot.gold,300000);
assert.equal(laserBoosterBonus(pilot),3,'X2 and X3 do not multiply');
const before=JSON.stringify(pilot);assert(!buyBooster(pilot,'damage3'));assert.equal(JSON.stringify(pilot),before);
tickBoosters(pilot,60,true);assert.equal(pilot.boosters.damage3,300);
tickBoosters(pilot,300,false);assert.equal(pilot.boosters.damage3,0);assert.equal(pilot.boosters.damage2,600);
tickBoosters(pilot,60,false);assert.equal(pilot.boosters.damage2,540);
pilot.boosters.damage=900;assert.equal(laserBoosterBonus(pilot),2);assert.equal(boosterBonus(pilot,'damage'),1.15,'legacy booster time retains its original effect');
const restored=JSON.parse(JSON.stringify(pilot));normalizeHangar(restored);assert.deepEqual(restored.boosters,pilot.boosters);
const timer={damage3:1,damage2:300};tickDamageBoosters(timer,2);assert.deepEqual(timer,{damage3:0,damage2:299});
assert.deepEqual(damageBoosterTimers({damage2:-1,damage3:'bad'}),{damage2:0,damage3:0});

const source={...pilot,shipId:'aurora',ownedShips:{aurora:true},shipBaseStats:{maxHp:100,attack:100,defense:0,speed:220},droneCount:1};
const roster=offlineRoster(source);
assert.equal(roster.profiles.aurora.boosters.damage2,540);
assert.equal(serializeHangarEditor(createHangarEditor(source),source).boosters.damage2,540);
const player={id:'a',pos:[0,0,0],connected:true},state={status:'active',players:[],bullets:[]};
makeCombatPlayer(player,{attack:100,droneCount:1,explorerDrone:true,boosters:{damage2:300}});
state.players=[player];player.boosterTickAt=10000;
const shot={offset:[0,0,-58],direction:[0,0,-1]};
assert.deepEqual(volley(state,player,{weapon:'laser',shots:[{...shot,kind:'laser'},{...shot,kind:'laser'},{...shot,kind:'drone'}]},10000).map(b=>b.damage),[300,300,120]);
assert.equal(volley(state,player,{weapon:'missile',shots:[shot]},10000)[0].damage,240);
assert.equal(volley(state,player,{weapon:'explorer',shots:[shot]},10000)[0].damage,60);
stepCombat(state,11000);assert.equal(player.profile.boosters.damage2,299);
player.hangar=true;stepCombat(state,21000);assert.equal(player.profile.boosters.damage2,299);
player.hangar=false;player.boostersPaused=true;stepCombat(state,22000);assert.equal(player.profile.boosters.damage2,299);
player.boostersPaused=false;stepCombat(state,23000);assert.equal(player.profile.boosters.damage2,298);
player.connected=false;stepCombat(state,24000);assert.equal(player.profile.boosters.damage2,298);
player.connected=true;player.hp=0;stepCombat(state,25000);assert.equal(player.profile.boosters.damage2,298);
player.profile.boosters={damage2:0,damage3:300};
assert.equal(volley(state,player,{weapon:'laser',shots:[shot]},26000)[0].damage,450);
const oldTime=player.profile.boosters.damage3;
player.roster=importRoster(roster.profiles);assert(equip(player,'aurora'));
assert.equal(player.profile.boosters.damage3,oldTime,'refreshing progress cannot restart an in-flight timer');
console.log('Damage boosters: prices, five minutes, queue, persistence, ship/drone damage, missiles and server pauses passed.');
