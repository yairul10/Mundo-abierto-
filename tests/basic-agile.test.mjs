import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SHIP_PREVIEWS} from '../js/ship-preview-catalog.js';
import {shipRole} from '../js/assembled-ships.js';
import {offlineRoster,pvpRoster,initialPvpPilot} from '../js/pvp-loadout.js';
import {importRoster,equip} from '../server/pvp/world-rules.mjs';
const base={maxHp:100,attack:100,defense:100,speed:100};
const pilot={shipId:'agilbasica',ownedShips:{aurora:true,agilbasica:true},shipBaseStats:base,maxEnergy:100};
assert.equal(offlineRoster({}).profiles.agilbasica,undefined,'New ship must be purchased');
assert.equal(initialPvpPilot(pilot).shipId,'agilbasica');
const pve=offlineRoster(pilot).profiles.agilbasica;
assert.deepEqual([pve.maxHp,pve.attack,pve.defense,pve.speed],[100,100,100,150]);
assert.equal(shipRole('agilbasica'),'aurora');
const arena=pvpRoster(pilot),player={roster:importRoster(arena.profiles)};
assert.equal(equip(player,'agilbasica'),true);
assert.equal(player.profile.shipId,'agilbasica');
assert.deepEqual([player.profile.maxHp,player.profile.attack,player.profile.defense,player.profile.speed],[1400,70,100,105]);
assert.deepEqual(pilot.shipBaseStats,base,'Switching into PvP must preserve saved base stats');
assert.equal(SHIP_PREVIEWS.aurora.model,'spaceplane.glb');
assert.equal(SHIP_PREVIEWS.agilbasica.model,'x_wing_starfighter.glb');
const glb=readFileSync(new URL('../assets/models/spaceplane.glb',import.meta.url));
assert.equal(glb.toString('ascii',0,4),'glTF');assert.equal(glb.readUInt32LE(4),2);assert.equal(glb.readUInt32LE(8),glb.length);
const json=JSON.parse(glb.toString('utf8',20,20+glb.readUInt32LE(12)));
assert.ok(json.meshes.length);assert.ok(json.buffers.every(b=>!b.uri),'Model is self contained for offline Android');
console.log('Basic agile ownership, PvE/PvP stats, server equip, original asset preservation and new GLB validation passed.');
